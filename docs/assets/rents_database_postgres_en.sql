-- =====================================================================
-- "Montreal Rents" database: star schema
-- Engine: PostgreSQL 12+ (derived from the SQLite script)
-- The grain of each fact table is given in a comment.
-- =====================================================================

-- ---------------------------------------------------------------- dimensions
CREATE TABLE dim_unit_type (
  unit_id   TEXT    PRIMARY KEY,                       -- studio, 1br, 2br, 3br
  label_fr  TEXT    NOT NULL UNIQUE,
  label_en  TEXT    NOT NULL,
  bedrooms  INTEGER NOT NULL CHECK (bedrooms BETWEEN 0 AND 3)
);

CREATE TABLE dim_city (                                   -- six large metro areas (CMHC annual series)
  geo_id    TEXT PRIMARY KEY,
  label_fr  TEXT NOT NULL,
  label_en  TEXT NOT NULL
);

CREATE TABLE dim_province (                              -- 10 provinces, 3 territories and Canada (aggregate)
  code   TEXT PRIMARY KEY CHECK (length(code) = 2),
  name   TEXT NOT NULL UNIQUE,
  level  TEXT NOT NULL CHECK (level IN ('province', 'territory', 'country'))
);

CREATE TABLE dim_estimate (                            -- type of estimate in table 46-10-0092
  code   TEXT PRIMARY KEY CHECK (code IN ('A', 'P')),
  label  TEXT NOT NULL UNIQUE                       -- A = asking rent, P = rent paid
);

CREATE TABLE dim_indicator (                            -- indicators from the CMHC report; the unit depends on the indicator alone (3NF)
  code   TEXT PRIMARY KEY,
  label  TEXT NOT NULL,
  unit   TEXT NOT NULL CHECK (unit IN ('dollars', 'pct'))
);

CREATE TABLE dim_metro_area (                                   -- 42 metro areas of table 46-10-0092 (+ all areas)
  geo_id    INTEGER PRIMARY KEY,
  name      TEXT    NOT NULL,
  province  TEXT    NOT NULL REFERENCES dim_province (code),
  lat       DOUBLE PRECISION    CHECK (lat IS NULL OR lat BETWEEN 41 AND 84),
  lon       DOUBLE PRECISION    CHECK (lon IS NULL OR lon BETWEEN -142 AND -52)
);

-- ---------------------------------------------------------------- facts
-- Grain: one year × one metro area × one unit type (October average rent, current dollars)
CREATE TABLE fact_rent (
  year     INTEGER NOT NULL CHECK (year BETWEEN 1987 AND 2100),
  geo_id   TEXT    NOT NULL REFERENCES dim_city (geo_id),
  unit_id  TEXT    NOT NULL REFERENCES dim_unit_type (unit_id),
  rent     INTEGER NOT NULL CHECK (rent > 0),
  PRIMARY KEY (year, geo_id, unit_id)
);

-- Grain: one year × one metro area (vacancy rate, buildings with 6 units or more, %)
CREATE TABLE fact_vacancy (
  year    INTEGER NOT NULL,
  geo_id  TEXT    NOT NULL REFERENCES dim_city (geo_id),
  rate    DOUBLE PRECISION    NOT NULL CHECK (rate BETWEEN 0 AND 100),
  PRIMARY KEY (year, geo_id)
);

-- Grain: one quarter × one metro area × one estimate (A = asking rent, P = rent paid), two-bedroom
CREATE TABLE fact_rent_quarterly (
  period    TEXT    NOT NULL CHECK (period ~ '^\d{4}-[01]\d$'),
  geo_id    INTEGER NOT NULL REFERENCES dim_metro_area (geo_id),
  estimate  TEXT    NOT NULL REFERENCES dim_estimate (code),
  rent      DOUBLE PRECISION    CHECK (rent IS NULL OR rent > 0),  -- NULL = not published by Statistics Canada
  grade     TEXT    CHECK (grade IS NULL OR grade IN ('E', 'F', '..')),
  PRIMARY KEY (period, geo_id, estimate)
);

-- Grain: one year × one large city (all-items CPI, annual average, 2002 = 100; Montreal)
CREATE TABLE cpi (
  year    INTEGER NOT NULL,
  geo_id  TEXT    NOT NULL REFERENCES dim_city (geo_id),
  cpi     DOUBLE PRECISION    NOT NULL CHECK (cpi > 0),
  PRIMARY KEY (year, geo_id)
);

-- Grain: one year × one province (rent CPI and all-items CPI, 2002 = 100)
CREATE TABLE cpi_provinces (
  year           INTEGER NOT NULL,
  code           TEXT    NOT NULL REFERENCES dim_province (code),
  rent_cpi       DOUBLE PRECISION    NOT NULL CHECK (rent_cpi > 0),
  all_items_cpi  DOUBLE PRECISION    NOT NULL CHECK (all_items_cpi > 0),
  PRIMARY KEY (year, code)
);

-- Grain: one year × one large city × one indicator published in the 2025 CMHC report
CREATE TABLE cmhc_turnover (
  year       INTEGER NOT NULL,
  geo_id     TEXT    NOT NULL REFERENCES dim_city (geo_id),
  indicator  TEXT    NOT NULL REFERENCES dim_indicator (code),
  value      DOUBLE PRECISION    NOT NULL,
  PRIMARY KEY (year, geo_id, indicator)
);

-- ---------------------------------------------------------------- index
CREATE INDEX ix_rent_geo_unit     ON fact_rent (geo_id, unit_id, year);
CREATE INDEX ix_quarter_geo_est       ON fact_rent_quarterly (geo_id, estimate, period);
CREATE INDEX ix_metro_province       ON dim_metro_area (province);
CREATE INDEX ix_cpip_code          ON cpi_provinces (code, year);

-- =====================================================================
-- Analytical views: the business logic lives in the database, not in each query
-- =====================================================================

-- Montreal rents in constant dollars of the latest available year
CREATE VIEW v_real_rent AS
WITH ref AS (SELECT year AS ref_year, cpi AS ref_cpi FROM cpi WHERE geo_id = 'Montreal' ORDER BY year DESC LIMIT 1)
SELECT f.year, f.unit_id, l.label_en AS unit_type, f.rent AS nominal_rent,
       ROUND((f.rent * r.ref_cpi / i.cpi)::numeric, 0) AS real_rent, r.ref_year
FROM fact_rent f
JOIN dim_unit_type l ON l.unit_id = f.unit_id
JOIN cpi i          ON i.year = f.year AND i.geo_id = f.geo_id
CROSS JOIN ref r
WHERE f.geo_id = 'Montreal';

-- Year-over-year change of each series (city × unit type)
CREATE VIEW v_annual_change AS
SELECT year, geo_id, unit_id, rent,
       LAG(rent) OVER w                                               AS prev_rent,
       ROUND((100.0 * (rent - LAG(rent) OVER w) / LAG(rent) OVER w)::numeric, 1) AS change_pct
FROM fact_rent
WINDOW w AS (PARTITION BY geo_id, unit_id ORDER BY year);

-- Latest published quarter of each series (metro area × estimate)
CREATE VIEW v_latest_quarter AS
SELECT geo_id, estimate, period, rent, grade
FROM (
  SELECT t.*, ROW_NUMBER() OVER (PARTITION BY geo_id, estimate ORDER BY period DESC) AS rn
  FROM fact_rent_quarterly t
  WHERE rent IS NOT NULL
) AS s
WHERE rn = 1;

-- Gap between asking rent and rent paid, by metro area
CREATE VIEW v_asking_paid_gap AS
SELECT r.geo_id, r.name, r.province,
       MAX(CASE WHEN d.estimate = 'A' THEN d.rent END) AS asking,
       MAX(CASE WHEN d.estimate = 'P' THEN d.rent END) AS paid,
       MAX(CASE WHEN d.estimate = 'A' THEN d.period END) AS period
FROM v_latest_quarter d
JOIN dim_metro_area r ON r.geo_id = d.geo_id
GROUP BY r.geo_id, r.name, r.province;

-- Rent increase (rent CPI) by province and year
CREATE VIEW v_cpi_provinces_change AS
SELECT i.year, i.code, p.name AS province, i.rent_cpi, i.all_items_cpi,
       ROUND((100.0 * (i.rent_cpi / LAG(i.rent_cpi) OVER w - 1))::numeric, 1)           AS rent_increase_pct,
       ROUND((100.0 * (i.all_items_cpi / LAG(i.all_items_cpi) OVER w - 1))::numeric, 1) AS inflation_pct
FROM cpi_provinces i
JOIN dim_province p ON p.code = i.code
WINDOW w AS (PARTITION BY i.code ORDER BY i.year);

